-- Traditional -> simplified folding covers the characters that occur in institution names of the seed and common bank
-- names (PROPOSAL, partial; a complete folding table is a later data task — F-C2-03).
create function bnx.normalize_institution_name(p text) returns text
language plpgsql immutable set search_path = pg_catalog, pg_temp as $$
declare s text;
begin
  if p is null then return null; end if;
  s := lower(normalize(p, NFKC));
  s := translate(s, '銀國業農設華發興豐滙匯東廣實聯會開證買賣灣際區恆寶資產鐵儲郵錢貸險長達遠頭門陽臺灃號務銷總滬漢與為點們這條義線際關',
                    '银国业农设华发兴丰汇汇东广实联会开证买卖湾际区恒宝资产铁储邮钱贷险长达远头门阳台沣号务销总沪汉与为点们这条义线际关');
  -- legal suffixes (zh, then en as whole words)
  s := regexp_replace(s, '(股份有限公司|有限责任公司|有限公司|股份公司|公司)$', '');
  s := regexp_replace(s, '\m(co|company|corp|corporation|inc|incorporated|ltd|limited|plc|llc|sa|ag|nv)\M\.?', ' ', 'g');
  s := regexp_replace(s, '\mthe\M', ' ', 'g');
  -- punctuation and whitespace (letters and digits of every script remain)
  s := regexp_replace(s, '[^[:alnum:]]+', '', 'g');
  return nullif(s, '');
end $$;

