-- ---------- data migration of existing institutions (one transaction) ----------
do $$
declare r record; keep uuid; n int; v bigint;
begin
  -- (0) jurisdiction from the R1 country column where it is a valid ISO code
  update bnx.institution set jurisdiction = upper(country) where country ~* '^[a-z]{2}$';
  -- (1) names of existing rows
  insert into bnx.institution_name(institution_id, name_kind, lang, value, normalized, verification, source)
  select i.id, 'display', x.lang, x.val, bnx.normalize_institution_name(x.val), 'UNVERIFIED', '{"source":"migration:9006 (R1 free text)"}'
    from bnx.institution i cross join lateral (values ('en', i.name_en), ('zh-CN', i.name_zh)) x(lang, val)
   where coalesce(x.val, '') <> '' and bnx.normalize_institution_name(x.val) is not null;
  -- (2) normalization match against the seed (display and legal names, both languages); never BIC
  create temp table seed_key on commit drop as
    select distinct s.code, k.norm from seed_inst s cross join lateral (values (bnx.normalize_institution_name(s.display_en)),
      (bnx.normalize_institution_name(s.display_zh)), (bnx.normalize_institution_name(s.legal_en)),
      (bnx.normalize_institution_name(s.legal_zh))) k(norm) where k.norm is not null;
  create temp table inst_match on commit drop as
    select i.id, (array_agg(distinct sk.code))[1] code, count(distinct sk.code) n_codes,
           coalesce((select min(a.created_at) from bnx.account a where a.institution_id = i.id), 'infinity') first_use
      from bnx.institution i join bnx.institution_name nm on nm.institution_id = i.id
      join seed_key sk on sk.norm = nm.normalized
     group by i.id;
  -- (3a) rows that match the same seed entry: the oldest is linked to the seed entry, the others are merged into it
  for r in select code, array_agg(id order by first_use, id) ids from inst_match where n_codes = 1 group by code loop
    keep := r.ids[1];
    update bnx.institution i set code = s.code, kind = s.kind, jurisdiction = s.jurisdiction, classification = s.classification,
           seed_set = s.seed_set, status = 'ACTIVE_SEED',
           verification_provenance = jsonb_build_object('source', 'seed INSTITUTION-REGISTRY-SEED-V1.0', 'linked_by', 'migration:9006 normalization')
      from seed_inst s where s.code = r.code and i.id = keep;
    for n in 2 .. coalesce(array_length(r.ids, 1), 1) loop
      update bnx.institution set status = 'MERGED_INTO', merged_into_id = keep where id = r.ids[n];
    end loop;
  end loop;
  update bnx.institution set status = 'PENDING_VERIFICATION' where id in (select id from inst_match where n_codes > 1);  -- ambiguous
  -- (3b) unmatched free-text duplicates (same normalized name and jurisdiction): oldest stays
  for r in select array_agg(i.id order by coalesce((select min(a.created_at) from bnx.account a where a.institution_id = i.id), 'infinity'), i.id) ids
             from bnx.institution i
            where i.status = 'PENDING_VERIFICATION' and i.code is null
            group by coalesce(bnx.normalize_institution_name(i.name_en), bnx.normalize_institution_name(i.name_zh), i.id::text),
                     coalesce(i.jurisdiction, '--')
           having count(*) > 1 loop
    for n in 2 .. array_length(r.ids, 1) loop
      update bnx.institution set status = 'MERGED_INTO', merged_into_id = r.ids[1] where id = r.ids[n];
    end loop;
  end loop;
  -- (4) INITIAL events for every existing account, then MERGE events re-pointing accounts of merged rows
  insert into bnx.account_institution_event(account_id, institution_id, reason, effective_from, recorded_version, authorization_ref)
  select a.id, a.institution_id, 'INITIAL', a.created_at::date,
         coalesce((select e.recorded_version from bnx.account_event e where e.account_id = a.id and e.event = 'created' order by e.seq limit 1), 0),
         'migration:9006'
    from bnx.account a where a.institution_id is not null order by a.created_at, a.id;
  select version into v from bnx.ledger_state;
  for r in select a.id acc, i.merged_into_id target, e.id prior
             from bnx.account a join bnx.institution i on i.id = a.institution_id and i.status = 'MERGED_INTO'
             join bnx.account_institution_event e on e.account_id = a.id loop
    insert into bnx.account_institution_event(account_id, institution_id, reason, effective_from, recorded_version, authorization_ref, prior_event_id)
    values (r.acc, r.target, 'MERGE', current_date, v, 'migration:9006', r.prior);
    update bnx.account set institution_id = r.target where id = r.acc;
  end loop;
  -- (5) grandfathering: existing accounts on unverified institutions keep posting and enter the Owner's verification queue
  update bnx.account a set institution_grandfathered = true
    from bnx.institution i where i.id = a.institution_id and i.status = 'PENDING_VERIFICATION';
  -- (6) seed entries not linked to an existing row (7: codes never reused)
  insert into bnx.institution(id, name_en, name_zh, country, code, kind, jurisdiction, classification, seed_set, status, verification_provenance)
  select gen_random_uuid(), s.display_en, s.display_zh, s.jurisdiction, s.code, s.kind, s.jurisdiction, s.classification, s.seed_set,
         'ACTIVE_SEED', jsonb_build_object('source', 'seed INSTITUTION-REGISTRY-SEED-V1.0')
    from seed_inst s where not exists (select 1 from bnx.institution i where i.code = s.code);
  insert into bnx.institution_name(institution_id, name_kind, lang, value, normalized, verification, source)
  select i.id, x.kind, x.lang, x.val, bnx.normalize_institution_name(x.val), x.ver, '{"source":"seed INSTITUTION-REGISTRY-SEED-V1.0"}'
    from seed_inst s join bnx.institution i on i.code = s.code
    cross join lateral (values ('display','en', s.display_en, 'VERIFIED'), ('display','zh-CN', s.display_zh, 'VERIFIED'),
                               ('legal','en', s.legal_en, coalesce(s.legal_verification, 'AUTHOR_CANDIDATE_SOURCE_REQUIRED')),
                               ('legal','zh-CN', s.legal_zh, coalesce(s.legal_verification, 'AUTHOR_CANDIDATE_SOURCE_REQUIRED'))) x(kind, lang, val, ver)
   where x.val is not null and bnx.normalize_institution_name(x.val) is not null;
  insert into bnx.retired_code values ('PSBC', null, 'reserved: known_not_seeded (Amendment 02); assigned only to a verified discovery');
  insert into bnx.brand(brand_code, brand_kind, display_en, display_zh, successor_brand)
  select brand_code, brand_kind, display_en, display_zh, successor_brand from seed_brand;
  insert into bnx.brand_issuer_event(brand_id, institution_id, effective_from, effective_to, source)
  select b.id, i.id, s.effective_from, s.effective_to, '{"source":"seed INSTITUTION-REGISTRY-SEED-V1.0"}'
    from seed_brand s join bnx.brand b on b.brand_code = s.brand_code join bnx.institution i on i.code = s.issuer_code;
  insert into bnx.institution_relationship_event(institution_id, related_institution_id, kind, effective_from, via_brand_id, source)
  select i.id, j.id, s.kind, s.effective_from, b.id, '{"source":"seed INSTITUTION-REGISTRY-SEED-V1.0"}'
    from seed_rel s join bnx.institution i on i.code = s.institution_code join bnx.institution j on j.code = s.related_code
    left join bnx.brand b on b.brand_code = s.via_brand;
  -- (6b) region backfill: institution jurisdiction; cash/other assets NONE; otherwise UNKNOWN (gated, Owner review)
  update bnx.account a set region_scope = coalesce(bnx.region_of_jurisdiction(i.jurisdiction), 'UNKNOWN')
    from bnx.institution i where i.id = a.institution_id;
  update bnx.account set region_scope = 'NONE' where institution_id is null and kind in ('cash','other_asset');
end $$;

