-- 5.4.4 (8): no path can create an account on an ineligible institution
create function bnx.trg_account_institution_eligible() returns trigger
language plpgsql set search_path = pg_catalog, pg_temp as $$
begin
  if bnx.restore_mode() then return new; end if;
  if new.institution_id is not null and not bnx.institution_eligible(new.institution_id) then
    raise exception 'INSTITUTION_NOT_ELIGIBLE' using errcode = 'P0422';
  end if;
  if new.region_scope = 'UNKNOWN' then raise exception 'JURISDICTION_REQUIRED' using errcode = 'P0422'; end if;
  return new;
end $$;
create trigger t_account_institution_eligible before insert on bnx.account
  for each row execute function bnx.trg_account_institution_eligible();

-- RR-02: account.institution_id changes only inside cmd_reassign_account_institution (xid-bound GUC)
create function bnx.trg_account_institution_guard() returns trigger
language plpgsql set search_path = pg_catalog, pg_temp as $$
begin
  if bnx.restore_mode() then return new; end if;
  if new.institution_id is distinct from old.institution_id
     and coalesce(current_setting('bnx.institution_reassign', true), '') <> pg_current_xact_id()::text then
    raise exception 'INSTITUTION_REASSIGN_REQUIRED' using errcode = 'P0409';
  end if;
  return new;
end $$;
create trigger t_account_institution_guard before update of institution_id on bnx.account
  for each row execute function bnx.trg_account_institution_guard();

create function bnx.trg_account_institution_projection() returns trigger
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare acc uuid; cur uuid; latest uuid;
begin
  if bnx.restore_mode() then return null; end if;
  if tg_table_name = 'account' then acc := new.id; else acc := new.account_id; end if;
  select institution_id into cur from bnx.account where id = acc;
  select institution_id into latest from bnx.account_institution_event where account_id = acc order by event_seq desc limit 1;
  if cur is distinct from latest then
    raise exception 'PROJECTION_DRIFT: account % institution % <> latest event %', acc, cur, latest using errcode = 'P0409';
  end if;
  return null;
end $$;
create constraint trigger t_account_institution_projection after insert or update of institution_id on bnx.account
  deferrable initially deferred for each row execute function bnx.trg_account_institution_projection();
create constraint trigger t_account_institution_projection after insert on bnx.account_institution_event
  deferrable initially deferred for each row execute function bnx.trg_account_institution_projection();

-- historical institution of an account at (date, ledger version); event_seq tie-break (R1 0104 pattern)
create function bnx.institution_at(p_account uuid, p_as_of date, p_v bigint) returns uuid
language sql stable security definer set search_path = pg_catalog, pg_temp as $$
  select institution_id from bnx.account_institution_event
   where account_id = p_account and effective_from <= p_as_of and recorded_version <= p_v
   order by effective_from desc, recorded_version desc, event_seq desc limit 1
$$;

-- issuer of a brand on a date (Amendment 02 §1: acquisitions never rewrite the historical issuer)
create function bnx.brand_issuer_at(p_brand text, p_on date) returns uuid
language sql stable security definer set search_path = pg_catalog, pg_temp as $$
  select e.institution_id from bnx.brand_issuer_event e join bnx.brand b on b.id = e.brand_id
   where b.brand_code = p_brand and (e.effective_from is null or e.effective_from <= p_on)
     and (e.effective_to is null or p_on < e.effective_to)
   order by e.event_seq desc limit 1
$$;

-- ---------- commands ----------
-- cmd_create_account MODIFY (same signature): institution by id or code, eligible only; region derived; first
-- account_institution_event in the same transaction; timezone from the financial policy. No institution is created from text.
create or replace function bnx.cmd_create_account(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); rc jsonb; acc uuid := gen_random_uuid(); inst uuid; cur text; ins record;
        la uuid; acid uuid; res jsonb := '[]'; v bigint; kind text := cmd->>'kind'; lkind text; vis text := coalesce(cmd->>'visibility','household');
        region text; tz text;
begin
  perform bnx.require(a, 2);
  rc := bnx.idem_begin(a, 'create_account', cmd); if rc is not null then return rc; end if;
  if kind not in ('bank_deposit','cash','e_wallet','credit_card','investment','loan_payable','loan_receivable','other_asset')
     or vis not in ('household','private') or coalesce(cmd->>'label','') = ''
     or jsonb_typeof(cmd->'currencies') <> 'array' or jsonb_array_length(cmd->'currencies') = 0 then
    perform bnx.fail('VALIDATION_FAILED', 'P0422', 'account');
  end if;
  if cmd ? 'institution' then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'institution_id or institution_code required (free-text institutions are not accepted)'); end if;
  if cmd ? 'institution_id' then
    inst := (cmd->>'institution_id')::uuid;
  elsif cmd ? 'institution_code' then
    select id into inst from bnx.institution where code = cmd->>'institution_code';
    if inst is null then perform bnx.fail('INSTITUTION_NOT_ELIGIBLE', 'P0422', 'unknown code'); end if;
  end if;
  if kind in ('cash','other_asset') then
    region := coalesce(cmd->>'region_scope', 'NONE');
    if inst is not null then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'cash/other_asset take no institution'); end if;
  else
    if inst is null then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'institution required'); end if;
    select * into ins from bnx.institution where id = inst;
    if not found or ins.status not in ('ACTIVE_SEED','VERIFIED_ACTIVE') then perform bnx.fail('INSTITUTION_NOT_ELIGIBLE', 'P0422'); end if;
    region := bnx.region_of_jurisdiction(ins.jurisdiction);
    if region is null then
      -- providers without a jurisdiction (wallets, networks): the account's region is declared (F-C2-05)
      region := cmd->>'region_scope';
    end if;
  end if;
  if region is null or region = 'UNKNOWN' or region !~ '^(CA|CN|HK|NONE|OTHER:[A-Z]{2})$' then
    perform bnx.fail('JURISDICTION_REQUIRED', 'P0422'); end if;
  if region = 'NONE' and kind not in ('cash','other_asset') then perform bnx.fail('JURISDICTION_REQUIRED', 'P0422', 'NONE is for cash/other assets'); end if;
  tz := coalesce((bnx.financial_policy_current()).household_timezone, 'America/Toronto');
  v := bnx.next_version();
  insert into bnx.account(id, kind, institution_id, label, reference_kind, reference_display, visibility, timezone, origin, state, created_by,
                          number_fingerprint, managed_reference, masked_display, region_scope)
  values (acc, kind, inst, cmd->>'label', case when cmd ? 'masked_display' then 'masked_number' else 'managed' end, cmd->>'masked_display',
          vis, tz, 'manual', 'active', a.member_id, decode(cmd->>'number_fingerprint', 'hex'), cmd->>'managed_reference',
          cmd->>'masked_display', region);
  if inst is not null then
    insert into bnx.account_institution_event(account_id, institution_id, reason, effective_from, recorded_version, actor_member_id)
    values (acc, inst, 'INITIAL', current_date, v, a.member_id);
  end if;
  lkind := case when kind in ('credit_card','loan_payable') then 'liability' else 'asset' end;
  for cur in select jsonb_array_elements_text(cmd->'currencies') loop
    if not exists (select 1 from bnx.currency where code = cur) then perform bnx.fail('UNKNOWN_CURRENCY', 'P0422', cur); end if;
    la := gen_random_uuid(); acid := gen_random_uuid();
    insert into bnx.ledger_account values (la, lkind, cur, (cmd->>'label') || ' ' || cur);
    insert into bnx.account_currency values (acid, acc, cur, la);
    res := res || jsonb_build_object('account_currency_id', acid, 'currency', cur, 'ledger_account_id', la);
  end loop;
  insert into bnx.account_grant(member_id, account_id, can_view, can_post, granted_by) values (a.member_id, acc, true, true, a.member_id);
  if vis = 'household' then
    insert into bnx.account_grant(member_id, account_id, can_view, can_post, granted_by)
    select m.id, acc, true, false, a.member_id from bnx.member m where m.state = 'active' and m.id <> a.member_id;
  end if;
  insert into bnx.account_event values (acc, 1, 'created', jsonb_build_object('label', cmd->>'label', 'visibility', vis), v, a.member_id, now());
  perform bnx.audit(a, 'create_account', jsonb_build_object('account_id', acc, 'institution_id', inst, 'region_scope', region), cmd, v);
  return bnx.idem_end(a, 'create_account', cmd, jsonb_build_object('account_id', acc, 'account_currencies', res, 'ledger_version', v,
                      'region_scope', region));
end $$;

-- RR-02 atomic reassignment (Owner T3, 15-minute freshness); the only runtime writer of account.institution_id
create function bnx.cmd_reassign_account_institution(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); role text; rc jsonb; acc record; tgt record; v bigint; prior uuid; e uuid;
        reason text := coalesce(cmd->>'reason', 'CORRECTION');
begin
  role := bnx.require(a, 3);
  if role <> 'owner' then perform bnx.fail('FORBIDDEN_ROLE', 'P0403'); end if;
  perform bnx.require_t3_fresh(a);
  rc := bnx.idem_begin(a, 'reassign_account_institution', cmd); if rc is not null then return rc; end if;
  if reason not in ('CORRECTION','BRAND_MIGRATION','VERIFICATION','MERGE') or coalesce(cmd->>'authorization_ref', '') = '' then
    perform bnx.fail('VALIDATION_FAILED', 'P0422', 'reason/authorization_ref'); end if;
  select * into acc from bnx.account where id = (cmd->>'account_id')::uuid for update;
  if not found or acc.institution_id is null then perform bnx.fail('NOT_FOUND', 'P0404'); end if;
  select * into tgt from bnx.institution where id = (cmd->>'institution_id')::uuid;
  if not found or tgt.status not in ('ACTIVE_SEED','VERIFIED_ACTIVE') then perform bnx.fail('INSTITUTION_NOT_ELIGIBLE', 'P0422'); end if;
  if tgt.id = acc.institution_id then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'same institution'); end if;
  v := bnx.next_version();
  select id into prior from bnx.account_institution_event where account_id = acc.id order by event_seq desc limit 1;
  insert into bnx.account_institution_event(account_id, institution_id, reason, effective_from, recorded_version, actor_member_id,
                                            authorization_ref, prior_event_id)
  values (acc.id, tgt.id, reason, coalesce((cmd->>'effective_from')::date, current_date), v, a.member_id, cmd->>'authorization_ref', prior)
  returning id into e;
  perform set_config('bnx.institution_reassign', pg_current_xact_id()::text, true);
  update bnx.account set institution_id = tgt.id,
         region_scope = coalesce(bnx.region_of_jurisdiction(tgt.jurisdiction), region_scope),
         institution_grandfathered = false
   where id = acc.id;
  perform set_config('bnx.institution_reassign', '', true);
  perform bnx.audit(a, 'reassign_account_institution', jsonb_build_object('account_id', acc.id, 'from', acc.institution_id, 'to', tgt.id,
                    'event_id', e), cmd, v);
  return bnx.idem_end(a, 'reassign_account_institution', cmd, jsonb_build_object('event_id', e, 'ledger_version', v));
end $$;

-- deterministic code from the English short name; jurisdiction suffix on collision; never a retired/reserved code
create function bnx.institution_code_for(p_name text, p_j text) returns text
language plpgsql stable set search_path = pg_catalog, pg_temp as $$
declare base text := left(regexp_replace(upper(regexp_replace(normalize(coalesce(p_name, ''), NFKC), '[^A-Za-z0-9]+', '_', 'g')), '^_+|_+$', '', 'g'), 30);
        c text; n int := 2;
begin
  if base !~ '^[A-Z]' then base := 'INST_' || base; end if;
  c := base;
  if exists (select 1 from bnx.institution where code = c) or exists (select 1 from bnx.retired_code where code = c) then
    c := base || '_' || coalesce(p_j, 'XX');
  end if;
  while exists (select 1 from bnx.institution where code = c) or exists (select 1 from bnx.retired_code where code = c) loop
    c := base || '_' || coalesce(p_j, 'XX') || '_' || n; n := n + 1;
  end loop;
  return c;
end $$;

-- RC-DRAFT: a candidate never activates anything (Amendment 02 §3 steps 2-5)
create function bnx.cmd_propose_institution_candidate(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); rc jsonb; norm text; j text := upper(cmd->>'jurisdiction'); key text; m uuid[]; c record;
        st text; cid uuid;
begin
  perform bnx.require(a, 1);
  rc := bnx.idem_begin(a, 'propose_institution_candidate', cmd); if rc is not null then return rc; end if;
  norm := coalesce(bnx.normalize_institution_name(cmd->>'name_en'), bnx.normalize_institution_name(cmd->>'name_zh'));
  if norm is null or (j is not null and j !~ '^[A-Z]{2}$') then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'name/jurisdiction'); end if;
  select coalesce(array_agg(distinct n.institution_id), '{}') into m from bnx.institution_name n join bnx.institution i on i.id = n.institution_id
   where n.normalized = norm and i.status in ('ACTIVE_SEED','VERIFIED_ACTIVE') and (j is null or i.jurisdiction is null or i.jurisdiction = j);
  if array_length(m, 1) = 1 then
    perform bnx.audit(a, 'propose_institution_candidate', jsonb_build_object('matched_institution_id', m[1]), cmd, null);
    return bnx.idem_end(a, 'propose_institution_candidate', cmd, jsonb_build_object('result', 'MATCHED', 'institution_id', m[1]));
  end if;
  key := norm || '|' || coalesce(j, '--') || '|' || coalesce((select string_agg(x->>'kind' || ':' || (x->>'value'), ',' order by x->>'kind', x->>'value')
                                                             from jsonb_array_elements(coalesce(cmd->'identifiers', '[]')) x), '');
  st := case when coalesce(array_length(m, 1), 0) > 1 then 'AMBIGUOUS' else 'PENDING_VERIFICATION' end;
  select * into c from bnx.institution_discovery_candidate where candidate_key = key for update;
  if found then
    update bnx.institution_discovery_candidate set evidence = evidence || coalesce(cmd->'evidence', '[]') where id = c.id;
    cid := c.id; st := c.state;
  else
    insert into bnx.institution_discovery_candidate(candidate_key, state, names, jurisdiction, identifiers, evidence, matched_institution_ids, proposed_by)
    values (key, st, jsonb_build_object('en', cmd->>'name_en', 'zh-CN', cmd->>'name_zh'), j, coalesce(cmd->'identifiers', '[]'),
            coalesce(cmd->'evidence', '[]'), m, a.member_id) returning id into cid;
  end if;
  perform bnx.audit(a, 'propose_institution_candidate', jsonb_build_object('candidate_id', cid, 'state', st), cmd, null);
  return bnx.idem_end(a, 'propose_institution_candidate', cmd, jsonb_build_object('result', st, 'candidate_id', cid));
end $$;

-- RC-DECLARE (Owner T3 with evidence reference): verifies a candidate or a pending institution; assigns the code
create function bnx.cmd_verify_institution(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); role text; rc jsonb; c record; i record; inst uuid; v_code text; j text;
        prov jsonb; decision text := coalesce(cmd->>'decision', 'verify');
begin
  role := bnx.require(a, 3);
  if role <> 'owner' then perform bnx.fail('FORBIDDEN_ROLE', 'P0403'); end if;
  perform bnx.require_t3_fresh(a);
  rc := bnx.idem_begin(a, 'verify_institution', cmd); if rc is not null then return rc; end if;
  if coalesce(cmd->>'evidence_ref', '') = '' then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'evidence_ref'); end if;
  prov := jsonb_build_object('evidence_ref', cmd->>'evidence_ref', 'verified_by', a.member_id, 'verified_at', now(), 'method', 'owner_t3');
  if cmd ? 'candidate_id' then
    select * into c from bnx.institution_discovery_candidate where id = (cmd->>'candidate_id')::uuid for update;
    if not found or c.state in ('VERIFIED','REJECTED') then perform bnx.fail('NOT_FOUND', 'P0404'); end if;
    if decision = 'reject' then
      update bnx.institution_discovery_candidate set state = 'REJECTED', resolved_at = now() where id = c.id;
    else
      j := coalesce(upper(cmd->>'jurisdiction'), c.jurisdiction);
      if j is null or j !~ '^[A-Z]{2}$' then perform bnx.fail('JURISDICTION_REQUIRED', 'P0422'); end if;
      v_code := coalesce(cmd->>'code', bnx.institution_code_for(coalesce(c.names->>'en', c.names->>'zh-CN'), j));
      if exists (select 1 from bnx.retired_code r where r.code = v_code) and v_code <> 'PSBC' then
        perform bnx.fail('CODE_RETIRED', 'P0409'); end if;
      inst := gen_random_uuid();
      insert into bnx.institution(id, name_en, name_zh, country, code, kind, jurisdiction, classification, status, verification_provenance)
      values (inst, c.names->>'en', c.names->>'zh-CN', j, v_code, coalesce(cmd->>'kind', 'bank'), j, cmd->>'classification',
              'VERIFIED_ACTIVE', prov || jsonb_build_object('candidate_id', c.id));
      insert into bnx.institution_name(institution_id, name_kind, lang, value, normalized, verification, source)
      select inst, 'display', x.lang, x.val, bnx.normalize_institution_name(x.val), 'VERIFIED', prov
        from (values ('en', c.names->>'en'), ('zh-CN', c.names->>'zh-CN')) x(lang, val) where coalesce(x.val, '') <> '';
      update bnx.institution_discovery_candidate set state = 'VERIFIED', institution_id = inst, resolved_at = now() where id = c.id;
    end if;
  else
    select * into i from bnx.institution where id = (cmd->>'institution_id')::uuid for update;
    if not found or i.status <> 'PENDING_VERIFICATION' then perform bnx.fail('NOT_FOUND', 'P0404'); end if;
    inst := i.id;
    if decision = 'reject' then
      update bnx.institution set status = 'REJECTED', verification_provenance = prov where id = i.id;
    else
      j := coalesce(upper(cmd->>'jurisdiction'), i.jurisdiction);
      if j is null or j !~ '^[A-Z]{2}$' then perform bnx.fail('JURISDICTION_REQUIRED', 'P0422'); end if;
      v_code := coalesce(cmd->>'code', bnx.institution_code_for(coalesce(i.name_en, i.name_zh), j));
      if exists (select 1 from bnx.retired_code r where r.code = v_code) and v_code <> 'PSBC' then
        perform bnx.fail('CODE_RETIRED', 'P0409'); end if;
      update bnx.institution set status = 'VERIFIED_ACTIVE', code = v_code, jurisdiction = j, kind = coalesce(cmd->>'kind', kind),
             classification = coalesce(cmd->>'classification', classification), verification_provenance = prov
       where id = i.id;
      -- grandfathered accounts leave the queue; their region follows the verified jurisdiction
      update bnx.account set institution_grandfathered = false,
             region_scope = case when region_scope = 'UNKNOWN' then bnx.region_of_jurisdiction(j) else region_scope end
       where institution_id = i.id;
    end if;
  end if;
  perform bnx.audit(a, 'verify_institution', jsonb_build_object('institution_id', inst, 'decision', decision, 'code', v_code), cmd, null);
  return bnx.idem_end(a, 'verify_institution', cmd, jsonb_build_object('institution_id', inst, 'code', v_code,
           'status', case when decision = 'reject' then 'REJECTED' else 'VERIFIED_ACTIVE' end));
end $$;

create function bnx.q_institutions_search(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); role text; norm text := bnx.normalize_institution_name(q->>'text'); v_lang text := coalesce(q->>'lang', 'en');
        pending boolean := coalesce((q->>'include_pending')::boolean, false);
begin
  role := bnx.require(a, 0);
  if pending and role <> 'owner' then pending := false; end if;
  return jsonb_build_object('institutions', coalesce((select jsonb_agg(jsonb_build_object('institution_id', i.id, 'code', i.code,
           'display', coalesce((select value from bnx.institution_name n where n.institution_id = i.id and n.name_kind = 'display' and n.lang = v_lang
                                 order by n.recorded_at desc limit 1), i.name_en, i.name_zh),
           'jurisdiction', i.jurisdiction, 'kind', i.kind, 'status', i.status) order by i.code nulls last, i.id)
      from bnx.institution i
     where (i.status in ('ACTIVE_SEED','VERIFIED_ACTIVE') or (pending and i.status = 'PENDING_VERIFICATION'))
       and (norm is null or exists (select 1 from bnx.institution_name n where n.institution_id = i.id and n.normalized like '%' || norm || '%')
            or i.code = upper(q->>'text'))), '[]'));
end $$;

-- Owner verification queue: pending institutions, grandfathered accounts, accounts whose region is UNKNOWN, candidates
create function bnx.q_registry_review(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); role text;
begin
  role := bnx.require(a, 0);
  if role <> 'owner' then perform bnx.fail('FORBIDDEN_ROLE', 'P0403'); end if;
  return jsonb_build_object(
    'pending_institutions', coalesce((select jsonb_agg(jsonb_build_object('institution_id', id, 'name_en', name_en, 'name_zh', name_zh,
                              'jurisdiction', jurisdiction) order by id) from bnx.institution where status = 'PENDING_VERIFICATION'), '[]'),
    'grandfathered_accounts', coalesce((select jsonb_agg(id order by id) from bnx.account where institution_grandfathered), '[]'),
    'unknown_region_accounts', coalesce((select jsonb_agg(id order by id) from bnx.account where region_scope = 'UNKNOWN'), '[]'),
    'candidates', coalesce((select jsonb_agg(jsonb_build_object('candidate_id', id, 'state', state, 'names', names) order by created_at)
                              from bnx.institution_discovery_candidate where state in ('PENDING_VERIFICATION','AMBIGUOUS')), '[]'),
    'financial_policy_unconfirmed', coalesce((bnx.financial_policy_current()).declared_by = 'installer', true));
end $$;

-- versioned Owner T3 declaration of the financial policy (confirms the installer's declaration)
create function bnx.cmd_declare_financial_policy(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); role text; rc jsonb; v int; cur bnx.financial_policy;
begin
  role := bnx.require(a, 3);
  if role <> 'owner' then perform bnx.fail('FORBIDDEN_ROLE', 'P0403'); end if;
  perform bnx.require_t3_fresh(a);
  rc := bnx.idem_begin(a, 'declare_financial_policy', cmd); if rc is not null then return rc; end if;
  cur := bnx.financial_policy_current();
  select coalesce(max(version), 0) + 1 into v from bnx.financial_policy;
  insert into bnx.financial_policy(version, reporting_currency, household_timezone, policy, declared_by, declared_member_id, confirmed_by, confirmed_at)
  values (v, coalesce(cmd->>'reporting_currency', cur.reporting_currency, 'CAD'), coalesce(cmd->>'household_timezone', cur.household_timezone, 'America/Toronto'),
          coalesce(cmd->'policy', cur.policy, '{}'), 'owner', a.member_id, a.member_id, now());
  perform bnx.audit(a, 'declare_financial_policy', jsonb_build_object('version', v), cmd, null);
  return bnx.idem_end(a, 'declare_financial_policy', cmd, jsonb_build_object('version', v));
end $$;

