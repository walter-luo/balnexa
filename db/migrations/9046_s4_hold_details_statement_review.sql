-- ---------- MODIFY bnx.intake_validate (9043) ----------
create or replace function bnx.intake_validate(p_plan uuid) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare pl record; acid uuid; acc record; ac record; it record; r jsonb := '{}'; holds text[] := '{}'; et text; why text; lines jsonb;
        vnow bigint; st jsonb; n int; x text; cont jsonb;   -- 9043 cont
        dt text;                                            -- 9046
begin
  select * into pl from bnx.posting_plan where id = p_plan for update;
  if not found then perform bnx.fail('NOT_FOUND', 'P0404'); end if;
  acid := (pl.scope->>'account_currency_id')::uuid;
  select * into ac from bnx.account_currency where id = acid;
  select * into acc from bnx.account where id = ac.account_id;
  select version into vnow from bnx.ledger_state;
  -- V-01 identity: account active; institution eligible (grandfathered accounts keep posting) or no institution (cash)
  if acc.id is null or acc.state <> 'active' or (acc.institution_id is not null and not bnx.institution_eligible(acc.institution_id)
                                                 and not acc.institution_grandfathered) then
    r := r || '{"V-01":"HOLD:IDENTITY"}'; holds := array_append(holds, 'IDENTITY');
  else r := r || '{"V-01":"ok"}'; end if;
  -- V-02 currency agreement of every line with its ledger account and of R1 items with the plan's account
  if exists (select 1 from bnx.posting_plan_item i cross join lateral jsonb_array_elements(bnx.plan_item_lines(p_plan, i.payload)) l
              join bnx.ledger_account la on la.id = (l->>'ledger_account_id')::uuid
             where i.plan_id = p_plan and la.currency <> l->>'currency')
     or exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan and i.payload ? 'currency' and i.payload->>'currency' <> ac.currency) then
    r := r || '{"V-02":"HOLD:CURRENCY"}'; holds := array_append(holds, 'CURRENCY');
  else r := r || '{"V-02":"ok"}'; end if;
  -- V-03 duplicates: source fingerprint repeated in the plan, already imported (source_txn) or in another live plan;
  --      evidence sha256 repeated in the plan
  if exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan and i.payload ? 'source_fingerprint'
              group by i.payload->>'source_fingerprint' having count(*) > 1)
     or exists (select 1 from bnx.posting_plan_item i join bnx.source_txn s on s.account_currency_id = acid
                  and encode(s.source_fingerprint, 'hex') = i.payload->>'source_fingerprint' where i.plan_id = p_plan)
     or exists (select 1 from bnx.posting_plan_item i join bnx.posting_plan_item o on o.payload->>'source_fingerprint' = i.payload->>'source_fingerprint'
                  join bnx.posting_plan op on op.id = o.plan_id and op.id <> p_plan
                   and op.state not in ('void','superseded','stale','suspended') and (op.scope->>'account_currency_id')::uuid = acid
                 where i.plan_id = p_plan and i.payload ? 'source_fingerprint')
     or exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan and i.payload ? 'evidence_sha256'
                 group by i.payload->>'evidence_sha256' having count(*) > 1) then
    r := r || '{"V-03":"HOLD:DUPLICATE"}'; holds := array_append(holds, 'DUPLICATE');
  else r := r || '{"V-03":"ok"}'; end if;
  -- V-04 statement balance chain: opening + rows = closing
  st := pl.scope->'statement';
  if st is not null then
    if (st->>'opening')::numeric + coalesce((select sum((i.payload->>'amount')::numeric) from bnx.posting_plan_item i where i.plan_id = p_plan), 0)
       <> (st->>'closing')::numeric then
      dt := 'ledger sign: opening ' || (st->>'opening') || ' + lines '                                                   -- 9046
            || trim_scale(coalesce((select sum((i.payload->>'amount')::numeric) from bnx.posting_plan_item i where i.plan_id = p_plan), 0))::text  -- 9046
            || ' = ' || trim_scale((st->>'opening')::numeric + coalesce((select sum((i.payload->>'amount')::numeric)        -- 9046
                                    from bnx.posting_plan_item i where i.plan_id = p_plan), 0))::text                       -- 9046
            || ', closing ' || (st->>'closing');                                                                            -- 9046
      r := r || jsonb_build_object('V-04', 'HOLD:BALANCE_CHAIN (' || dt || ')'); holds := array_append(holds, 'BALANCE_CHAIN');  -- 9046
    else r := r || '{"V-04":"ok"}'; end if;
  else r := r || '{"V-04":"n/a"}'; end if;
  -- V-05 coverage: a statement period overlapping an already approved/activated statement plan of the same account-currency
  if st is not null and exists (select 1 from bnx.posting_plan o where o.id <> p_plan and o.scope ? 'statement'
        and (o.scope->>'account_currency_id')::uuid = acid and o.state in ('approved','executing','sealed','activated')
        and daterange((o.scope->'statement'->>'period_from')::date, (o.scope->'statement'->>'period_to')::date, '[]')
            && daterange((st->>'period_from')::date, (st->>'period_to')::date, '[]')) then
    r := r || '{"V-05":"HOLD:COVERAGE"}'; holds := array_append(holds, 'COVERAGE');
  else r := r || jsonb_build_object('V-05', case when st is null then 'n/a' else 'ok' end); end if;
  -- V-06 fingerprints present for every row of an import
  if pl.kind = 'import' and exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan
                                     and coalesce(i.payload->>'source_fingerprint', '') = '') and coalesce((pl.scope->>'require_fingerprints')::boolean, false) then
    r := r || '{"V-06":"HOLD:FINGERPRINT"}'; holds := array_append(holds, 'FINGERPRINT');
  else r := r || jsonb_build_object('V-06', case when coalesce((pl.scope->>'require_fingerprints')::boolean, false) then 'ok' else 'n/a' end); end if;
  -- V-07 economic-type rule pre-check (B6.1, 9008) on every item
  n := 0;
  for it in select * from bnx.posting_plan_item where plan_id = p_plan order by seq loop
    et := bnx.plan_item_economic_type(it.payload);
    why := case when et is null then 'untyped' else bnx.economic_type_violation_lines(et, bnx.plan_item_lines(p_plan, it.payload)) end;
    if why is not null then n := n + 1; x := coalesce(x, 'seq ' || it.seq || ': ' || why); end if;
  end loop;
  if n > 0 then r := r || jsonb_build_object('V-07', 'HOLD:ECONOMIC_TYPE (' || x || ')'); holds := array_append(holds, 'ECONOMIC_TYPE');
  else r := r || '{"V-07":"ok"}'; end if;
  -- V-08 transfer pairs: both legs present (typed lines on two account-currencies) or the counter leg is a clearing account
  if exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan
              and bnx.plan_item_economic_type(i.payload) in ('internal_transfer','card_repayment')
              and not exists (select 1 from jsonb_array_elements(bnx.plan_item_lines(p_plan, i.payload)) l
                                join bnx.ledger_account la on la.id = (l->>'ledger_account_id')::uuid where la.kind = 'clearing')
              and (select count(distinct ac2.id) from jsonb_array_elements(bnx.plan_item_lines(p_plan, i.payload)) l
                     join bnx.account_currency ac2 on ac2.ledger_account_id = (l->>'ledger_account_id')::uuid) < 2) then
    r := r || '{"V-08":"HOLD:TRANSFER_PAIR"}'; holds := array_append(holds, 'TRANSFER_PAIR');
  else r := r || '{"V-08":"ok"}'; end if;
  -- V-09 review queue: rows marked for review (uncategorized / needs_review) hold the plan
  if exists (select 1 from bnx.posting_plan_item i where i.plan_id = p_plan
              and (coalesce((i.payload->>'needs_review')::boolean, false) or (not i.payload ? 'lines' and not i.payload ? 'counter_ledger_account_id'))) then
    select string_agg(i.seq::text, ', ' order by i.seq) into dt from bnx.posting_plan_item i where i.plan_id = p_plan      -- 9046
       and (coalesce((i.payload->>'needs_review')::boolean, false) or (not i.payload ? 'lines' and not i.payload ? 'counter_ledger_account_id'));  -- 9046
    r := r || jsonb_build_object('V-09', 'HOLD:REVIEW_QUEUE (seq ' || dt || ')'); holds := array_append(holds, 'REVIEW_QUEUE');  -- 9046
  else r := r || '{"V-09":"ok"}'; end if;
  -- V-10 module flag of the plan's scope (9007)
  begin
    perform bnx.pol_require_module_for_ac(acid);
    r := r || '{"V-10":"ok"}';
  exception when sqlstate 'P0403' then
    r := r || jsonb_build_object('V-10', 'HOLD:SCOPE (' || sqlerrm || ')'); holds := array_append(holds, 'SCOPE');
  end;
  -- V-11 statement continuity (9043): the opening balance meets the closing balance of the nearest earlier live statement of
  --      the same account-currency. A break holds the plan unless a member recorded an explanation; a calendar gap with
  --      matching balances is a finding only (no activity is the usual cause)
  if st is not null then                                                                                                 -- 9043
    cont := bnx.statement_continuity(p_plan);                                                                            -- 9043
    if cont->>'status' = 'break' then                                                                                    -- 9043
      r := r || jsonb_build_object('V-11', 'HOLD:BALANCE_BREAK (previous closing ' || (cont->>'previous_closing') || ' on '   -- 9043
                                   || (cont->>'previous_period_to') || ', opening ' || (cont->>'opening') || ')');        -- 9043
      holds := array_append(holds, 'BALANCE_BREAK');                                                                     -- 9043
    elsif cont->>'status' = 'gap' then                                                                                   -- 9043
      r := r || jsonb_build_object('V-11', 'FINDING:GAP (' || (cont->>'gap_from') || '..' || (cont->>'gap_to') || ')');   -- 9043
    else r := r || jsonb_build_object('V-11', cont->>'status'); end if;                                                  -- 9043
  else r := r || '{"V-11":"n/a"}'; end if;                                                                               -- 9043
  -- V-12 opening anchor (9043): no item may fall before the opening anchor of a household account it touches; the posting
  --      worker would refuse it after approval (POSTINGS_BEFORE_ANCHOR). For history the anchor moves to the earliest statement
  if exists (select 1 from bnx.posting_plan_item i                                                                       -- 9043
               cross join lateral jsonb_array_elements(bnx.plan_item_lines(p_plan, i.payload)) l                          -- 9043
               join bnx.account_currency x on x.ledger_account_id = (l->>'ledger_account_id')::uuid                        -- 9043
              where i.plan_id = p_plan                                                                                    -- 9043
                and (i.payload->>'transaction_date')::date < (bnx.anchor_at(x.id, 9223372036854775807)).anchor_date) then -- 9043
    -- 9046: name the items (seq and date) and the opening date they fall before; the account is not named, since an AI
    --       connection may not see the other account
    select string_agg(z.t, '; ' order by z.seq) into dt from (                                                           -- 9046
      select distinct i.seq, 'seq ' || i.seq || ' ' || (i.payload->>'transaction_date') || ' before opening '               -- 9046
             || (bnx.anchor_at(x.id, 9223372036854775807)).anchor_date::text t                                              -- 9046
        from bnx.posting_plan_item i cross join lateral jsonb_array_elements(bnx.plan_item_lines(p_plan, i.payload)) l      -- 9046
        join bnx.account_currency x on x.ledger_account_id = (l->>'ledger_account_id')::uuid                                -- 9046
       where i.plan_id = p_plan                                                                                            -- 9046
         and (i.payload->>'transaction_date')::date < (bnx.anchor_at(x.id, 9223372036854775807)).anchor_date) z;           -- 9046
    r := r || jsonb_build_object('V-12', 'HOLD:BEFORE_OPENING (' || dt || ')'); holds := array_append(holds, 'BEFORE_OPENING');  -- 9046
  else r := r || '{"V-12":"ok"}'; end if;                                                                                -- 9043
  update bnx.posting_plan set validation_result = r, hold_reasons = holds, validated_at_version = last_validated_version where id = p_plan;
  return jsonb_build_object('validation_result', r, 'hold_reasons', to_jsonb(holds), 'validated_at_version', pl.last_validated_version);
end $$;

-- ---------- MODIFY bnx.q_draft_get_for_confirmation (9045) ----------
create or replace function bnx.q_draft_get_for_confirmation(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); pl record;
        acc record;                                                                                                        -- 9045
begin
  perform bnx.require(a, case when a.channel = 'mcp' then 1 else 0 end);
  select * into pl from bnx.posting_plan where id = (q->>'plan_id')::uuid;
  if not found or not ((pl.scope->>'account_currency_id')::uuid in (select bnx.actor_visible_acs(a)))
     or (a.channel = 'mcp' and pl.origin_ai_connection_id is distinct from a.connection_id) then
    perform bnx.fail('NOT_AVAILABLE', 'P0404'); end if;
  select ac.id, ac.currency, x.label, x.masked_display into acc from bnx.account_currency ac                                -- 9045
    join bnx.account x on x.id = ac.account_id where ac.id = (pl.scope->>'account_currency_id')::uuid;                     -- 9045
  return jsonb_build_object('plan_id', pl.id, 'kind', pl.kind, 'state', pl.state, 'plan_hash', encode(pl.plan_hash, 'hex'),
    'scope_digest', encode(pl.scope_digest, 'hex'), 'validation_result', pl.validation_result, 'hold_reasons', to_jsonb(pl.hold_reasons),
    'created_by', pl.created_by, 'origin_channel', pl.origin_channel,
    'account_currency_id', acc.id, 'account_label', acc.label, 'account_currency', acc.currency,                         -- 9045
    'account_reference_display', acc.masked_display, 'statement', pl.scope->'statement',                                -- 9045
    'items', (select jsonb_agg(jsonb_build_object('seq', i.seq, 'payload', i.payload, 'economic_type', bnx.plan_item_economic_type(i.payload),
                                                  'lines', (select jsonb_agg(l || jsonb_build_object(                     -- 9045
                                                     'ledger_account_name', bnx.ledger_account_display(l->>'ledger_account_id', 'en'),  -- 9045
                                                     'ledger_account_name_zh', bnx.ledger_account_display(l->>'ledger_account_id', 'zh')) -- 9045
                                                     order by n)                                                          -- 9045
                                                     from jsonb_array_elements(bnx.plan_item_lines(pl.id, i.payload)) with ordinality e(l, n))) -- 9045
                                  order by i.seq)
                from bnx.posting_plan_item i where i.plan_id = pl.id),
    'approvable_by_me', a.channel = 'pwa' and bnx.actor_can_post(a, (pl.scope->>'account_currency_id')::uuid)
                        and pl.state = 'frozen' and cardinality(pl.hold_reasons) = 0,
    -- 9046: a member who could approve the account may review a statement draft line by line (category, reviewed)
    'reviewable_by_me', a.channel = 'pwa' and pl.scope ? 'statement' and pl.state = 'frozen'                              -- 9046
                        and bnx.actor_can_post(a, (pl.scope->>'account_currency_id')::uuid));                              -- 9046
end $$;


-- ---------- NEW bnx.cmd_review_statement_items ----------
-- G3 (F-LIVE-2): a member who may post to the statement's account reviews an open statement draft line by line in the PWA:
-- a line's category (or, for a transfer or card payment, the other household account) and "reviewed" (clears needs_review).
-- Dates, amounts, descriptions and fingerprints are the statement's and never change here. The result is a new version that
-- supersedes the one the member saw (plan_hash must match); it keeps the kind and the AI connection of that version, so the
-- AI still sees its draft, and the member approves it as usual.
create function bnx.cmd_review_statement_items(cred jsonb, cmd jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); rc jsonb; r jsonb; pl record; ac record; acc record; ch jsonb; it record; p jsonb;
        items jsonb := '[]'; chg jsonb := '{}'; k text; s int; cla record; cac record; amt numeric; et text; n int := 0; st jsonb;
begin
  perform bnx.require(a, 2);
  if a.channel = 'mcp' then perform bnx.fail('FORBIDDEN_CHANNEL', 'P0403'); end if;
  rc := bnx.idem_begin(a, 'review_statement_items', cmd); if rc is not null then return rc; end if;
  begin
    select * into pl from bnx.posting_plan where id = (cmd->>'plan_id')::uuid for update;
  exception when invalid_text_representation then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'plan_id');
  end;
  if not found or not pl.scope ? 'statement'
     or not ((pl.scope->>'account_currency_id')::uuid in (select bnx.actor_visible_acs(a))) then
    perform bnx.fail('NOT_AVAILABLE', 'P0404'); end if;
  if not bnx.actor_can_post(a, (pl.scope->>'account_currency_id')::uuid) then perform bnx.fail('NOT_POSTABLE', 'P0403'); end if;
  if pl.state <> 'frozen' then perform bnx.fail('PLAN_NOT_REVISABLE', 'P0409', pl.state); end if;
  if encode(pl.plan_hash, 'hex') is distinct from cmd->>'plan_hash' then perform bnx.fail('PLAN_DIGEST_MISMATCH', 'P0409'); end if;
  if jsonb_typeof(cmd->'changes') is distinct from 'array' or jsonb_array_length(cmd->'changes') = 0
     or jsonb_array_length(cmd->'changes') > 1000 then
    perform bnx.fail('VALIDATION_FAILED', 'P0422', 'changes: 1 to 1000'); end if;
  select * into ac from bnx.account_currency where id = (pl.scope->>'account_currency_id')::uuid;
  select * into acc from bnx.account where id = ac.account_id;
  -- collect the changes per seq (one change per line)
  for ch in select * from jsonb_array_elements(cmd->'changes') loop
    if jsonb_typeof(ch) <> 'object' then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'change'); end if;
    for k in select jsonb_object_keys(ch) loop
      if not k = any(array['seq','counter_ledger_account_id','economic_type','reviewed']) then
        perform bnx.fail('VALIDATION_FAILED', 'P0422', 'change field ' || k); end if;
    end loop;
    begin s := (ch->>'seq')::int;
    exception when invalid_text_representation or numeric_value_out_of_range then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'seq'); end;
    if s is null or not exists (select 1 from bnx.posting_plan_item where plan_id = pl.id and seq = s) or chg ? s::text then
      perform bnx.fail('VALIDATION_FAILED', 'P0422', 'seq ' || coalesce(s::text, 'null')); end if;
    if not (ch ? 'counter_ledger_account_id' or ch ? 'economic_type' or ch ? 'reviewed') then
      perform bnx.fail('VALIDATION_FAILED', 'P0422', 'change for seq ' || s || ' is empty'); end if;
    if ch ? 'reviewed' and jsonb_typeof(ch->'reviewed') is distinct from 'boolean' then
      perform bnx.fail('VALIDATION_FAILED', 'P0422', 'reviewed'); end if;
    if ch ? 'economic_type' and (ch->>'economic_type' in ('opening_balance','correction_reversal','correction_replacement',
                                   'interledger_transfer','clearing_resolution')
        or not exists (select 1 from bnx.economic_type_rule where economic_type::text = ch->>'economic_type')) then
      perform bnx.fail('VALIDATION_FAILED', 'P0422', 'economic_type'); end if;
    chg := chg || jsonb_build_object(s::text, ch);
  end loop;
  -- rebuild every item; only the reviewed fields change
  for it in select * from bnx.posting_plan_item where plan_id = pl.id order by seq loop
    p := it.payload;
    ch := chg->(it.seq::text);
    if ch is not null then
      n := n + 1;
      -- the line's amount on the statement account (typed items carry it as their plan-account line)
      amt := coalesce((p->>'amount')::numeric,
                      (select sum((l->>'amount')::numeric) from jsonb_array_elements(p->'lines') l
                        where (l->>'ledger_account_id')::uuid = ac.ledger_account_id));
      if ch ? 'counter_ledger_account_id' then
        begin
          select * into cla from bnx.ledger_account where id = (ch->>'counter_ledger_account_id')::uuid;
        exception when invalid_text_representation then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'counter_ledger_account_id');
        end;
        if not found or cla.currency <> ac.currency or cla.id = ac.ledger_account_id then
          perform bnx.fail('VALIDATION_FAILED', 'P0422', 'counter_ledger_account_id (seq ' || it.seq || ')'); end if;
        select * into cac from bnx.account_currency where ledger_account_id = cla.id;
        p := p - 'lines' - 'counter_ledger_account_id' - 'economic_type';
        if cac.id is not null then
          -- another household account: a transfer or a card payment, as typed lines
          if not (cac.id in (select bnx.actor_visible_acs(a))) then perform bnx.fail('NOT_AVAILABLE', 'P0404'); end if;
          et := coalesce(ch->>'economic_type', case when acc.kind = 'credit_card' and cla.kind = 'asset' then 'card_repayment'
                                                     when cla.kind = 'liability' and acc.kind <> 'credit_card' and amt < 0
                                                          and (select kind from bnx.account where id = cac.account_id) = 'credit_card'
                                                          then 'card_repayment'
                                                     else 'internal_transfer' end);
          p := p || jsonb_build_object('economic_type', et, 'lines', jsonb_build_array(
                 jsonb_build_object('ledger_account_id', ac.ledger_account_id, 'currency', ac.currency, 'amount', trim_scale(amt)::text),
                 jsonb_build_object('ledger_account_id', cla.id, 'currency', ac.currency, 'amount', trim_scale(-amt)::text)));
        elsif cla.kind in ('income','expense') then
          p := p || jsonb_build_object('counter_ledger_account_id', cla.id, 'amount', trim_scale(amt)::text);
          if ch ? 'economic_type' then p := p || jsonb_build_object('economic_type', ch->>'economic_type'); end if;
        else
          perform bnx.fail('VALIDATION_FAILED', 'P0422', 'counter_ledger_account_id (seq ' || it.seq || '): a category or an account');
        end if;
      elsif ch ? 'economic_type' then
        p := p || jsonb_build_object('economic_type', ch->>'economic_type');
      end if;
      if coalesce((ch->>'reviewed')::boolean, false) then p := p - 'needs_review'; end if;
    end if;
    items := items || jsonb_build_array(p);
  end loop;
  st := pl.scope->'statement';
  perform bnx.plan_terminate(pl.id, 'superseded', 'revised by member review');
  r := bnx.plan_create(a, pl.kind, jsonb_build_object('account_currency_id', ac.id, 'date_from', st->>'period_from',
         'date_to', st->>'period_to', 'items', items, 'evidence_file_ids', coalesce(pl.scope->'evidence_file_ids', '[]'::jsonb),
         'supersedes_plan_id', pl.id, 'require_fingerprints', coalesce(pl.scope->'require_fingerprints', 'true'::jsonb),
         'statement', st));
  -- the AI connection that submitted the statement keeps seeing (and may correct) its draft
  update bnx.posting_plan set origin_ai_connection_id = pl.origin_ai_connection_id where id = (r->>'plan_id')::uuid;
  r := r || jsonb_build_object('continuity', bnx.statement_continuity((r->>'plan_id')::uuid), 'changed', n);
  perform bnx.audit(a, 'review_statement_items', jsonb_build_object('plan_id', pl.id, 'new_plan_id', r->>'plan_id', 'changed', n), cmd, null);
  return bnx.idem_end(a, 'review_statement_items', cmd, r);
