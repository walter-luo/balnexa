-- no catalog query returned the audit chain.
--   NEW: bnx.q_audit_trail (tier 0; PWA channel only - not in function_scope, so never an MCP tool). The Owner and admins
--        see every event; any other member sees the events they caused. Filters: command prefix, member, date range,
--        paging by seq (before_seq), limit <= 500. Returned per event: seq, time, member (id and display name), channel,
--        command, subject, ledger version, chain version, host profile and tool name (AI-host provenance, 9005). The
--        payload itself is never stored in the chain (only its SHA-256), so it cannot be returned.
set role bnx_definer;

create function bnx.q_audit_trail(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); rl text; lim int; bef bigint; d0 date; d1 date; mem uuid; pre text := q->>'command'; rows_ jsonb;
begin
  rl := bnx.require(a, 0);
  begin
    lim := least(greatest(coalesce((q->>'limit')::int, 100), 1), 500);
    bef := (q->>'before_seq')::bigint;
    d0 := (q->>'date_from')::date; d1 := (q->>'date_to')::date;
    mem := (q->>'member_id')::uuid;
  exception when others then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'limit, before_seq, date_from, date_to or member_id'); end;
  if pre is not null and pre !~ '^[a-z_]{1,64}$' then perform bnx.fail('VALIDATION_FAILED', 'P0422', 'command'); end if;
  select coalesce(jsonb_agg(x order by (x->>'seq')::bigint desc), '[]') into rows_ from (
    select jsonb_build_object('seq', e.seq, 'at', e.at, 'member_id', e.member_id, 'member', m.display_name, 'channel', e.channel,
             'command', e.command, 'subject', e.subject, 'ledger_version', e.ledger_version, 'chain_version', e.chain_version,
             'host_profile', e.host_profile, 'tool_name', e.tool_name) x
      from bnx_audit.audit_event e left join bnx.member m on m.id = e.member_id
     where (rl in ('owner','admin') or e.member_id = a.member_id)
       and (bef is null or e.seq < bef) and (pre is null or e.command like pre || '%')
       and (mem is null or e.member_id = mem)
       and (d0 is null or e.at >= d0::timestamptz) and (d1 is null or e.at < (d1 + 1)::timestamptz)
     order by e.seq desc limit lim) t;
  return jsonb_build_object('events', rows_, 'scope', case when rl in ('owner','admin') then 'household' else 'own' end,
    'next_before_seq', case when jsonb_array_length(rows_) = lim then (rows_->(lim - 1)->>'seq')::bigint end);
end $$;

select bnx.apply_grants();

