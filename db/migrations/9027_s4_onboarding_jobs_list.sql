--   NEW: bnx.q_onboarding_jobs (PWA): the onboarding jobs the caller may see (own jobs; all jobs for the Owner and admins, the
--        same rule as q_onboarding_job), newest first, with kind, title, start policy and state at the current ledger version.
--        No file names or amounts; details stay behind q_onboarding_job.
set role bnx_definer;

create function bnx.q_onboarding_jobs(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); vnow bigint;
begin
  perform bnx.require(a, 0);
  select version into vnow from bnx.ledger_state;
  return jsonb_build_object('jobs', coalesce((select jsonb_agg(jsonb_build_object('job_id', j.id, 'kind', j.kind, 'title', j.title,
           'start_policy', j.scope->>'start_policy', 'state', bnx.onboarding_state_at(j.id, vnow), 'created_at', j.created_at)
           order by j.created_at desc, j.id)
         from bnx.onboarding_job j where j.created_by = a.member_id or bnx.onboarding_admin(a)), '[]'));
end $$;

