-- against, and no catalog query returned ledger_account_id values (F1/F2 return account-currencies and names only).
--   NEW: bnx.q_ledger_accounts (tier 0; PWA channel only - not in function_scope, so never an MCP tool): the caller's visible
--        account-currencies with their ledger account, label, kind, institution code, state and whether the caller can post
--        to it (bnx.actor_can_post), plus the household's active income and expense categories (latest category_version).
--   Catalog: the delta block below holds only this function's entry (D-CORE9-2; generated by tools/s4/catalog_build.py).
set role bnx_definer;

create function bnx.q_ledger_accounts(cred jsonb, q jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare a bnx.actor := bnx.resolve_actor(cred); acs jsonb; cats jsonb;
begin
  perform bnx.require(a, 0);
  select coalesce(jsonb_agg(jsonb_build_object('account_currency_id', ac.id, 'ledger_account_id', ac.ledger_account_id, 'account_id', acc.id,
           'label', acc.label, 'kind', acc.kind, 'currency', ac.currency, 'state', acc.state, 'institution_code', i.code,
           'institution', i.name_en, 'can_post', bnx.actor_can_post(a, ac.id))
           order by acc.state, i.code nulls last, acc.label, ac.currency), '[]')
    into acs
    from bnx.actor_visible_acs(a) x join bnx.account_currency ac on ac.id = x join bnx.account acc on acc.id = ac.account_id
    left join bnx.institution i on i.id = acc.institution_id;
  select coalesce(jsonb_agg(jsonb_build_object('ledger_account_id', l.id, 'kind', l.kind, 'currency', l.currency,
           'name_en', c.name_en, 'name_zh', c.name_zh) order by l.kind, l.currency, c.name_en), '[]')
    into cats
    from bnx.ledger_account l
    join lateral (select cv.name_en, cv.name_zh, cv.state from bnx.category_version cv where cv.category_id = l.id
                   order by cv.valid_from_version desc limit 1) c on true
   where l.kind in ('income','expense') and c.state = 'active';
  return jsonb_build_object('accounts', acs, 'categories', cats);
end $$;

select bnx.apply_grants();

