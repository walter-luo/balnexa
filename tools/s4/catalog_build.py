#!/usr/bin/env python3
"""bnx-tools/1.0 catalog generator (UA V1.2 §8; AIH V1.2 §2, DD-21; CORE-7).

Derives one catalog entry per REST-callable function (every bnx.cmd_*/q_* function that bnx_app may EXECUTE) from the
function itself, so the PWA, REST and MCP cannot drift:
  * kind and core_function from the name (schema-qualified);
  * tier / risk class from the body: the highest N in bnx.require(a, N) (including "case ... then N"), or the tier of a
    helper listed in db/catalog/bnx-tools-1.0.overrides.json; a function whose tier cannot be read and is not listed
    there is an ERROR (no silent default);
  * scopes, MCP tool name, legacy flags and account-currency subset from bnx.function_scope (9009+);
  * input_schema: every key the body reads from its jsonb argument (->>, ->, ?, #>>), typed from a direct cast
    ((x->>'k')::uuid|date|timestamptz|int|bigint|numeric|boolean) and permissive otherwise; additionalProperties stays
    true (the database remains the validator of record; the schema rejects wrong types early); idempotency_key is never
    in the schema: the database reports IDEMPOTENCY_KEY_REQUIRED itself (identical codes on every surface, AT-AIH-05).

Output: COMMENT ON FUNCTION blocks between markers. 9017 holds the full catalog of its time; every later migration that
adds or changes a REST-callable function carries a **delta block** with only the entries that differ from the merge of the
earlier blocks (D-CORE9-2: a committed migration is never edited). The effective catalog is the merge of all blocks in
migration order.
Usage:
  catalog_build.py --server pg16 --db <migrated db> --write [--into FILE]  # write the delta block into the newest marked
                                                                          # migration (or FILE) before it is committed
  catalog_build.py --server pg16 --db <migrated db> --check     # exit 1 if the merged blocks differ from the derivation
  catalog_build.py --server pg16 --db <migrated db> --json OUT  # also write the entries as JSON
"""
import argparse, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tests", "py"))
import harness as h  # noqa: E402
import psycopg  # noqa: E402

MIGDIR = os.path.join(ROOT, "db", "migrations")
LINE = re.compile(r"^comment on function ([a-z_]+)\.([a-z0-9_]+)\(jsonb, jsonb\) is \$c\$(.*)\$c\$;$")
OVR = os.path.join(ROOT, "db", "catalog", "bnx-tools-1.0.overrides.json")
BEGIN, END = "-- @@CATALOG-BEGIN (generated by tools/s4/catalog_build.py; do not edit)", "-- @@CATALOG-END"
RISK = {0: "RC-READ", 1: "RC-DRAFT", 2: "RC-POST", 3: "RC-ADMIN"}
CARD_URI = "ui://balnexa/cards/v1"            # AIH-4: the one MCP App resource (AIH V1.2 §8)
TYPES = {
    "uuid": {"type": "string", "format": "uuid"},
    "date": {"type": "string", "format": "date"},
    "timestamptz": {"type": "string", "format": "date-time"},
    "integer": {"type": ["integer", "string"], "pattern": "^-?[0-9]{1,18}$"},
    "numeric": {"type": ["number", "string"], "pattern": "^-?[0-9]{1,24}(\\.[0-9]{1,12})?$"},
    "boolean": {"type": ["boolean", "string"], "enum": [True, False, "true", "false"]},
    "array": {"type": "array"},
    "object": {"type": "object"},
}
CAST = {"uuid": "uuid", "date": "date", "timestamptz": "timestamptz", "timestamp": "timestamptz", "int": "integer", "integer": "integer",
        "bigint": "integer", "smallint": "integer", "numeric": "numeric", "boolean": "boolean", "bool": "boolean"}
COMMON_ERRORS = ["UNAUTHENTICATED", "FORBIDDEN_ROLE", "FORBIDDEN_CHANNEL", "FORBIDDEN_SCOPE", "SCOPE_NOT_CONSENTED", "NOT_AVAILABLE",
                 "VALIDATION_FAILED", "SCOPE_DISABLED", "BNX_BINDING_MISMATCH", "BNX_FLAG_BINDING_MISMATCH"]


def derive(cx, ovr):
    rows = cx.execute("""
      select n.nspname, p.proname, p.prosrc, pg_get_function_identity_arguments(p.oid)
        from pg_proc p join pg_namespace n on n.oid = p.pronamespace
       where n.nspname in (select nspname from bnx.schema_registry) and (p.proname like 'cmd\\_%' or p.proname like 'q\\_%')
         and has_function_privilege('bnx_app', p.oid, 'EXECUTE')
       order by p.proname""").fetchall()
    fscope = {r[0]: r[1:] for r in cx.execute(
        "select function_name, scope, legacy_read, legacy_propose, needs_ac_subset, note from bnx.function_scope").fetchall()}
    entries, errors = [], []
    for nsp, name, src, args in rows:
        if args not in ("cred jsonb, cmd jsonb", "cred jsonb, q jsonb"):
            errors.append(f"{name}: unexpected signature ({args})"); continue
        par = "cmd" if args.endswith("cmd jsonb") else "q"
        kind = "command" if name.startswith("cmd_") else "query"
        tiers = [int(t) for t in re.findall(r"bnx\.require\(\s*a\s*,\s*(\d)\s*\)", src)]
        for blk in re.findall(r"bnx\.require\(\s*a\s*,\s*case\b(.*?)\bend\s*\)", src, re.S):
            tiers += [int(t) for t in re.findall(r"\b(?:then|else)\s+(\d)\b", blk)]
        for hlp, t in ovr["tier_helpers"].items():
            if re.search(rf"bnx\.{hlp}\(\s*a\s*\)", src):
                tiers.append(t)
        public = name in ovr.get("public", [])
        if not tiers and not public:
            errors.append(f"{name}: tier not derivable and not listed in {os.path.relpath(OVR, ROOT)}"); continue
        tier = max(tiers) if tiers else None
        props = {}
        keys = set(re.findall(rf"\b{par}\s*(?:->>|->|\?)\s*'([a-z][a-z_0-9]*)'", src)) | \
            set(re.findall(rf"\b{par}\s*#>>?\s*'\{{([a-z][a-z_0-9]*)", src))
        for k in sorted(keys - {"idempotency_key"}):
            casts = {CAST[c] for c in re.findall(rf"\(\s*{par}\s*->>\s*'{k}'\s*\)\s*::\s*([a-z]+)", src) if c in CAST}
            if re.search(rf"jsonb_array_elements(?:_text)?\(\s*{par}\s*->\s*'{k}'\s*\)|jsonb_array_length\(\s*{par}\s*->\s*'{k}'\s*\)", src):
                casts.add("array")
            props[k] = dict(TYPES[next(iter(casts))]) if len(casts) == 1 else {}
        fs = fscope.get(name)
        tool = fs[4] if fs and fs[4] and re.fullmatch(r"[a-z]+(\.[a-z0-9_]+)+", fs[4]) else None
        mcp = bool(fs) and tier is not None and tier <= 1
        e = {
            "name": ovr.get("names", {}).get(name) or tool or f"pwa.{name.split('_', 1)[1]}",
            "version": "1.0.0",
            "kind": kind,
            "rest": f"/api/v1/{'commands' if kind == 'command' else 'queries'}/{name.split('_', 1)[1]}",
            "core_function": f"{nsp}.{name}",
            "risk_class": "RC-PUBLIC" if public else RISK[tier],
            "tier": tier,
            "scopes": [fs[0]] if fs and fs[0] else [],
            "legacy": {"read": bool(fs and fs[1]), "propose": bool(fs and fs[2])},
            "needs_ac_subset": bool(fs and fs[3]),
            "channels": ["pwa"] + (["mcp"] if mcp else []),
            "module_flags": [],
            "input_schema": {"type": "object", "properties": props, "additionalProperties": True},
            "output_schema": {"type": "object"},
            "errors": COMMON_ERRORS,
            "idempotency": "required" if re.search(r"bnx\.idem_begin\(", src) else "none",
            "masked_fields": [],
            "evidence_citation": name.startswith("q_f") or name in ("q_cashflow_statement", "q_evidence_trace", "q_r28_loan_position"),
            "mcp": {"readOnlyHint": tier == 0, "destructiveHint": False, "openWorldHint": False,
                    "ui_resource": CARD_URI if mcp and name in ovr.get("ui_cards", {}) else None},
            "ui_profile": ovr.get("ui_cards", {}).get(name) if mcp else None,
            "description": ovr.get("descriptions", {}).get(name, f"{kind} {name.split('_', 1)[1]}"),
            "provenance": "derived",
        }
        entries.append((nsp, name, e))
    seen = {}
    for _, name, e in entries:
        if e["name"] in seen:
            errors.append(f"tool name {e['name']} used by {seen[e['name']]} and {name}")
        seen[e["name"]] = name
    return entries, errors


def block(entries):
    out = [BEGIN]
    for nsp, name, e in entries:
        j = json.dumps(e, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
        assert "$c$" not in j
        out.append(f"comment on function {nsp}.{name}(jsonb, jsonb) is $c${j}$c$;")
    out.append(END)
    return "\n".join(out)


def marked():
    """migration files carrying a catalog block, in migration order"""
    out = []
    for f in sorted(os.listdir(MIGDIR)):
        if f.endswith(".sql"):
            src = open(os.path.join(MIGDIR, f)).read()
            if BEGIN in src and END in src:
                out.append(os.path.join(MIGDIR, f))
    return out


def parse(path):
    src = open(path).read()
    i, j = src.find(BEGIN), src.find(END)
    got = {}
    for line in src[i + len(BEGIN):j].strip().splitlines():
        m = LINE.match(line)
        if not m:
            raise SystemExit(f"catalog_build: unparsable line in {os.path.basename(path)}: {line[:80]}")
        got[(m.group(1), m.group(2))] = json.loads(m.group(3))
    return src, i, j, got


def merged(paths):
    eff = {}
    for p in paths:
        eff.update(parse(p)[3])
    return eff


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", required=True)
    ap.add_argument("--db", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--json")
    ap.add_argument("--into")
    a = ap.parse_args()
    ovr = json.load(open(OVR))
    with psycopg.connect(h.dsn(a.server, "bnx_migrator", a.db)) as cx:
        cx.execute("set role bnx_definer")
        entries, errors = derive(cx, ovr)
    if errors:
        print("catalog_build: ERRORS\n  " + "\n  ".join(errors)); sys.exit(2)
    if a.json:
        json.dump([e for _, _, e in entries], open(a.json, "w"), indent=1, sort_keys=True)
    files = marked()
    if not files:
        print("catalog_build: no migration carries catalog markers"); sys.exit(2)
    want = {(nsp, name): e for nsp, name, e in entries}
    if a.write:
        target = os.path.abspath(a.into) if a.into else files[-1]
        newest = os.path.join(MIGDIR, sorted(f for f in os.listdir(MIGDIR) if f.endswith(".sql"))[-1])
        if not a.into and target != newest:
            # never rewrite the block of an earlier (committed) migration by default: the newest migration must carry markers
            print(f"catalog_build: the newest migration {os.path.basename(newest)} has no catalog markers; add them or pass --into"); sys.exit(2)
        if target not in files:
            print("catalog_build: markers missing in " + target); sys.exit(2)
        before = merged(files[:files.index(target)])
        delta = [(nsp, name, e) for nsp, name, e in entries if before.get((nsp, name)) != e]
        stale = sorted(k for k in before if k not in want)
        if stale:
            print("catalog_build: functions no longer REST-callable keep an earlier entry: " + ", ".join(".".join(k) for k in stale)); sys.exit(2)
        src, i, j, _ = parse(target)
        open(target, "w").write(src[:i] + block(delta) + src[j + len(END):])
        print(f"catalog_build: wrote {len(delta)} of {len(entries)} entries into {os.path.basename(target)}")
        return
    eff = merged(files)
    missing = sorted(".".join(k) for k in want if eff.get(k) != want[k])
    extra = sorted(".".join(k) for k in eff if k not in want)
    if missing or extra:
        print(f"catalog_build: DRIFT: merged blocks of {len(files)} migration(s) differ from the derivation; differing: {missing[:10]}; "
              f"no longer callable: {extra[:10]}"); sys.exit(1)
    print(f"catalog_build: OK, {len(entries)} entries match (blocks in {', '.join(os.path.basename(f)[:4] for f in files)})")


if __name__ == "__main__":
    main()
