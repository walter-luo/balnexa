def pdf_incremental(val):                                                 # AT-SIN-03: value in revision 0, removed in revision 1
    base, x = write({1: b"<< /Type /Catalog /Pages 2 0 R >>", 2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
                     3: b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
                     4: stream(b"", text_ops(["Synthetic slip", "Recipient number " + val])), 5: FONT}, b"/Root 1 0 R")
    out, _ = write({4: stream(b"", text_ops(["Synthetic slip", "Recipient number [redacted]"]))}, b"/Root 1 0 R", base=base, prev=x)
    return out


