"""Synthetic document fixtures for the 9011c validator tests (AT-SIN-01..07, 13, 29, 30, 31).

Every fixture is built in memory at test time from values generated by sin_corpus.value(); nothing here is a real document
and the repository holds no SIN-shaped literal (guard C6). PDFs are written by hand (objects, xref, trailer) so that each
hiding place is exactly the one under test: content streams are Flate-compressed and strings in dictionaries are written
as hex strings, so a raw byte search cannot see the value and only the extraction path under test can.
"""
import email.message
import email.policy
import io
import zlib

import sin_corpus as SC


def hexstr(t):
    return b"<FEFF" + t.encode("utf-16-be").hex().upper().encode() + b">"


def stream(d, data, compress=True):
    if compress:
        data = zlib.compress(data)
        d = d + b" /Filter /FlateDecode"
    return b"<< " + d + b" /Length " + str(len(data)).encode() + b" >>\nstream\n" + data + b"\nendstream"


def _xref(entries):
    out = b""
    for n, off in entries:
        out += b"%d 1\n%010d 00000 n \n" % (n, off)
    return out


def write(objs, trailer, base=None, prev=None):
    """objs: {num: body}; trailer: dictionary body (without << >>); base: bytes of the earlier revision (incremental update)."""
    out = bytearray(base if base is not None else b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offs = {}
    for n in sorted(objs):
        offs[n] = len(out)
        out += b"%d 0 obj\n" % n + objs[n] + b"\nendobj\n"
    x = len(out)
    if base is None:
        size = max(objs) + 1
        out += b"xref\n0 %d\n0000000000 65535 f \n" % size
        for n in range(1, size):
            out += b"%010d 00000 n \n" % offs[n]
    else:
        size = max(objs) + 1
        out += b"xref\n0 1\n0000000000 65535 f \n" + _xref(sorted(offs.items()))
    t = b"<< /Size %d " % size + trailer + (b" /Prev %d" % prev if prev is not None else b"") + b" >>"
    out += b"trailer\n" + t + b"\nstartxref\n%d\n%%%%EOF\n" % x
    return bytes(out), x


def text_ops(lines, y=700, size=12):
    ops = b"BT /F1 %d Tf 72 %d Td %d TL\n" % (size, y, size + 4)
    for ln in lines:
        ops += b"(" + ln.encode("latin-1") + b") Tj T*\n"
    return ops + b"ET\n"


FONT = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"


def nums(*n):
    """Graphics operands built at run time (a literal like a rectangle of three-digit coordinates would itself look like a
    nine-digit number to the repository scan, guard C6)."""
    return b" ".join(b"%d" % x for x in n)


def simple_pdf(content, extra_objs=None, page_extra=b"", catalog_extra=b"", info=None, trailer_extra=b"", resources_extra=b""):
    """1 catalog, 2 pages, 3 page, 4 content, 5 font, 6.. extra."""
    objs = {1: b"<< /Type /Catalog /Pages 2 0 R " + catalog_extra + b" >>",
            2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            3: b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> "
               + resources_extra + b" >> " + page_extra + b" >>",
            4: stream(b"", content),
            5: FONT}
    objs.update(extra_objs or {})
    tr = b"/Root 1 0 R " + trailer_extra
    if info is not None:
        n = max(objs) + 1
        objs[n] = info
        tr += b" /Info %d 0 R" % n
    return write(objs, tr)[0]


