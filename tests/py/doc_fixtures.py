# ---------------------------------------------------------------------------------------------------------- images
def image(lines, redact=None, size=44, fmt="PNG", exif_text=None):
    """A synthetic scan: black text on white, optionally a black box over line index `redact`."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.load_default(size=size)
    im = Image.new("RGB", (1400, 120 + 90 * len(lines)), "white")
    dr = ImageDraw.Draw(im)
    for i, ln in enumerate(lines):
        dr.text((60, 60 + 90 * i), ln, fill="black", font=font)
        if redact is not None and i == redact[0]:
            x0 = 60 + dr.textlength(ln[:redact[1]], font=font)
            dr.rectangle([x0 - 6, 50 + 90 * i, 60 + dr.textlength(ln, font=font) + 6, 60 + 90 * i + size + 12], fill="black")
    buf = io.BytesIO()
    kw = {}
    if exif_text is not None:
        ex = Image.Exif()
        ex[0x010E] = exif_text                      # ImageDescription
        kw["exif"] = ex
    im.save(buf, format=fmt, **kw)
    return buf.getvalue(), im.size


def damaged_png():
    data, _ = image(["Synthetic"])
    return data[:len(data) // 3]


# ---------------------------------------------------------------------------------------------------------- XLSX
def xlsx(very_hidden=None, comment=None, prop=None, clean_rows=None, macro=False):
    import openpyxl
    from openpyxl.comments import Comment
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Summary"
    for r in clean_rows or [["Account", "Balance"], ["Chequing", "1234.56"]]:
        ws.append(r)
    if very_hidden is not None:
        h = wb.create_sheet("Data")
        h.append(["ref", very_hidden])
        h.sheet_state = "veryHidden"
    if comment is not None:
        ws["B2"].comment = Comment("Ref " + comment, "Synthetic")
    if prop is not None:
        wb.properties.keywords = "ref " + prop
    buf = io.BytesIO()
    wb.save(buf)
    data = buf.getvalue()
    if macro:
        import zipfile
        src = zipfile.ZipFile(io.BytesIO(data))
        out = io.BytesIO()
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
            for i in src.infolist():
                z.writestr(i, src.read(i))
            z.writestr("xl/vbaProject.bin", b"\x00" * 64)
        data = out.getvalue()
    return data


def zip_archive(val):
    import zipfile
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        z.writestr("inner.txt", "ref " + val)
    return out.getvalue()


# ---------------------------------------------------------------------------------------------------------- EML
def eml(body="Synthetic statement attached.", attachments=()):
    m = email.message.EmailMessage(policy=email.policy.default)
    m["From"] = "bank@example.invalid"
    m["To"] = "owner@example.invalid"
    m["Subject"] = "Synthetic statement"
    m["Message-ID"] = "<synthetic-1@example.invalid>"
    m.set_content(body)
    for name, ctype, data in attachments:
        if ctype == "message/rfc822":
            m.add_attachment(email.message_from_bytes(data, policy=email.policy.default), filename=name)
        else:
            mt, st = ctype.split("/")
            m.add_attachment(data, maintype=mt, subtype=st, filename=name)
    return m.as_bytes()


def eml_nested(val):                                                      # AT-SIN-06: value in an attachment of an attached message
    inner = eml("Forwarded slip.", attachments=[("slip.csv", "text/csv", ("ref,amount\n" + val + ",52000\n").encode())])
    return eml("See the forwarded message.", attachments=[("forwarded.eml", "message/rfc822", inner)])


